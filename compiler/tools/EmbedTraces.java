// Writes the Elm module Stepper.Examples: every <tracesDir>/*.json as
// ( base name, JSON text ), sorted by name, for the stepper's start screen.
// Usage: java -cp compiler/tools-bin EmbedTraces traces src/Stepper/Examples.elm

import java.io.File;
import java.nio.file.Files;
import java.util.Arrays;

public class EmbedTraces {

  public static void main(String[] args) throws Exception {
    if (args.length != 2) fail("usage: EmbedTraces <tracesDir> <outFile.elm>");
    File[] files = new File(args[0]).listFiles();
    if (files == null) fail("no directory " + args[0]);
    Arrays.sort(files);

    StringBuilder b = new StringBuilder();
    b.append("-- GENERATED by compiler/tools/EmbedTraces.java. Do not edit.\n\n\n");
    b.append("module Stepper.Examples exposing (examples)\n\n\n");
    b.append("examples : List ( String, String )\n");
    b.append("examples =\n");
    int count = 0;
    for (File f : files) {
      String name = f.getName();
      if (!name.endsWith(".json")) continue;
      String json = new String(Files.readAllBytes(f.toPath()), "US-ASCII");   // traces are pure ASCII
      b.append(count == 0 ? "    [ ( " : "    , ( ")
       .append(quote(name.substring(0, name.length() - 5))).append(", ").append(quote(json)).append(" )\n");
      count++;
    }
    b.append(count == 0 ? "    []\n" : "    ]\n");
    Files.write(new File(args[1]).toPath(), b.toString().getBytes("US-ASCII"));
    System.out.println("Embedded " + count + " traces in " + args[1]);
  }

  // An Elm string literal. The JSON is already ASCII, so only these five need escaping.
  static String quote(String s) {
    StringBuilder b = new StringBuilder(s.length() + 16).append('"');
    for (int k = 0; k < s.length(); k++) {
      char c = s.charAt(k);
      switch (c) {
        case '\\': b.append("\\\\"); break;
        case '"':  b.append("\\\""); break;
        case '\n': b.append("\\n"); break;
        case '\r': b.append("\\r"); break;
        case '\t': b.append("\\t"); break;
        default:   b.append(c);
      }
    }
    return b.append('"').toString();
  }

  static void fail(String why) {
    System.err.println("EmbedTraces: " + why);
    System.exit(2);
  }
}
